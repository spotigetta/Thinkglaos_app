import {chromium} from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true});
const seed=JSON.parse(fs.readFileSync('public/data/seed.json','utf8'));
await page.route('https://raw.githubusercontent.com/**',r=>r.fulfill({json:seed}));
await page.route('https://api.github.com/**',r=>r.fulfill({json:{sha:'qa',content:Buffer.from(JSON.stringify(seed)).toString('base64')}}));
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:3000/');
await page.waitForTimeout(800);
await page.screenshot({path:'.local/new-welcome.png'});
console.log('Mobile overflow:',await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
await page.getByRole('button',{name:'Vídeos Ver y compartir'}).click();
await page.waitForTimeout(1000);
const audio=page.getByLabel('Audio de Manolo Lama');
await audio.evaluate(a=>a.play());
await page.waitForTimeout(500);
console.log('Audio:',await audio.evaluate(a=>({duration:a.duration,playing:!a.paused,error:a.error?.message||null})));
await audio.evaluate(a=>a.pause());
await page.screenshot({path:'.local/new-media.png'});
await page.locator('.youtube-card').first().getByRole('button').click();
await page.waitForTimeout(2500);
const frame=page.frames().find(f=>f.url().includes('youtube-nocookie.com/embed/'));
console.log('YouTube:',frame? (await frame.locator('body').innerText()).slice(0,600):'No iframe');
await page.getByRole('tab',{name:'Material del equipo',exact:true}).click();
const video=page.locator('video').filter({visible:true}).first();
await video.evaluate(v=>{v.muted=true;return v.play()}).catch(e=>console.log('Original video:',e.message.slice(0,300)));
await page.waitForTimeout(1200);
console.log('Native video:',await video.evaluate(v=>({src:v.currentSrc,duration:v.duration,playing:!v.paused,error:v.error?.message||null})));
console.log('JS errors:',errors);
await browser.close();
